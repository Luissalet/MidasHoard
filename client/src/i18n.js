export function initialLang() {
  try {
    const saved = localStorage.getItem("midas-lang");
    if (saved === "es" || saved === "en") return saved;
  } catch {
    // storage may be blocked; fall back to the browser language
  }
  return (navigator.language || "es").toLowerCase().startsWith("en") ? "en" : "es";
}

export function saveLang(lang) {
  try {
    localStorage.setItem("midas-lang", lang);
  } catch {
    // not critical
  }
}

export function makeT(lang) {
  const dict = DICT[lang] || DICT.es;
  return (key, vars) => {
    let value = dict[key];
    if (value === undefined) return key;
    if (vars) for (const [name, v] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, v);
    return value;
  };
}
